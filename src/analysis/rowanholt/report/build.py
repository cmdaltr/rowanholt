HASH_DIGITS = 12
FORMATS = ("markdown", "docx")
SUFFIXES = {"markdown": ".md", "docx": ".docx"}


def _when(iso: str) -> str:
    """An ISO time as the report shows it: to the second, UTC kept as Z."""
    if not iso:
        return ""
    text = iso.replace("T", " ")
    text = re.sub(r"\.\d+", "", text)
    return text


def _plural(count: int, word: str, plural: str = "") -> str:
    return f"{count:,} {word if count == 1 else plural or word + 's'}"


def _short(row_hash: str) -> str:
    return row_hash[:HASH_DIGITS]


def _cite_cells(cite: Cite) -> List:
    return [[(cite.file, "code")], cite.ref, [(_short(cite.row_hash), "code")]]


def _excerpt(cite: Cite) -> str:
    return cite.excerpt + (f" (parsed from {cite.source})" if cite.source else "")


def _technique_label(report: CaseReport, tid: str) -> str:
    technique = report.techniques.get(tid)
    return f"{tid} {technique.name}" if technique and technique.name else tid


# ---- the uncurated report ----

def _introduction(report: CaseReport) -> List[Block]:
    tagged = [t for t in report.techniques.values() if t.rows]
    return [
        Para([("Generated by Rowanholt on ", ""), (_when(report.generated), ""), (" from the case directory ", ""),
              (report.root, "code"), (". It is built from the case alone: no analyst has reviewed what it lists, "
                                      "so each technique and indicator is what Elrond tagged or extracted, not a "
                                      "confirmed finding.", "")]),
        Para(f"{_plural(len(report.hosts), 'host')}; {_plural(len(report.techniques), 'ATT&CK technique')} "
             f"({len(tagged)} with rows behind them); "
             f"{_plural(sum(h.ioc_rows for h in report.hosts), 'indicator occurrence')}."),
        Heading(2, "Reading the citations"),
        Para([("Every row is cited by host, file and row. The file is relative to the host's folder in the case, "
               "as the case browser lists it; the row is the line number in a JSON Lines or CSV file (a CSV's header "
               "is line 1), or ", ""), ("#n", "code"), (" in an old case's JSON array. The hash is the first "
                                                         f"{HASH_DIGITS} hex digits of the row's SHA-256, computed as "
                                                         "the case browser and findings compute it, so a row that a "
                                                         "re-run changed no longer matches. \"Parsed from\" names "
                                                         "the collected file the row came from, in the host's ", ""),
              ("artefacts/raw/", "code"), (".", "")]),
    ]


def _hosts(report: CaseReport) -> List[Block]:
    blocks: List[Block] = [Heading(2, "Hosts and timespan")]
    rows = []
    for host in report.hosts:
        collected = (_span(host.collected_from, host.collected_to) if host.collected_from
                     else "not by Gandalf" if not host.integrity.gandalf else "no times in gandalf_log.audit")
        processed = _span(host.processed_from, host.processed_to) if host.processed_from else ""
        rows.append([host.name, host.os or "not recorded", f"{host.tables:,}", f"{host.records:,}", collected, processed])
    blocks.append(Table(["Host", "OS", "Tables", "Records", "Collected (Gandalf)", "Processed (Elrond)"], rows,
                        [3, 2, 1, 2, 4, 4]))
    sources = sorted({f"{h.name}: {h.os_cite}" for h in report.hosts if h.os_cite})
    if sources:
        blocks.append(Para("OS as recorded in " + "; ".join(sources) + "."))
    earliest, latest = report.earliest, report.latest
    if earliest and latest:
        blocks.append(Para([("Record times run from ", ""), (_when(earliest.time), "b"), (f" ({earliest.host}) to ", ""),
                            (_when(latest.time), "b"), (f" ({latest.host}).", "")]))
    firsts = [h.first_technique for h in report.hosts if h.first_technique]
    lasts = [h.last_technique for h in report.hosts if h.last_technique]
    if firsts:
        first = min(firsts, key=lambda c: c.time)
        last = max(lasts, key=lambda c: c.time)
        blocks.append(Para([("Rows tagged with a technique run from ", ""), (_when(first.time), "b"),
                            (f" ({first.host}) to ", ""), (_when(last.time), "b"), (f" ({last.host}).", "")]))
    blocks.append(Para("A record's time is its envelope's timestamp, or the artefact's own time where the envelope "
                       "has none. File system tables (the MFT, the USN journal) carry the operating system's own "
                       "file times, so the earliest record is usually older than the activity; the technique rows "
                       "are the narrower window."))
    evidence = []
    for host in report.hosts:
        for label, cite in (("earliest record", host.earliest), ("latest record", host.latest),
                            ("first technique row", host.first_technique), ("last technique row", host.last_technique)):
            if cite:
                evidence.append([host.name, label, _when(cite.time), *_cite_cells(cite), _excerpt(cite)])
    if evidence:
        blocks.append(Table(["Host", "Which", "Time", "File", "Row", "Hash", "Row (excerpt)"], evidence,
                            [3, 3, 4, 5, 1, 3, 8]))
    untimed = [h.name for h in report.hosts if h.records and not h.timed]
    if untimed:
        blocks.append(Para(f"No record times on {', '.join(untimed)}: the tables are CSV and JSON from before records "
                           "carried a normalised time, so no timespan is given from them."))
    unreadable = [[host.name, [(name, "code")], problem] for host in report.hosts for name, problem in host.unreadable]
    if unreadable:
        blocks.append(Para(f"{_plural(len(unreadable), 'table')} couldn't be read, so nothing in "
                           f"{'it' if len(unreadable) == 1 else 'them'} is in this report:"))
        blocks.append(Table(["Host", "File", "Problem"], unreadable, [3, 6, 6]))
    return blocks


def _span(start: str, end: str) -> str:
    return f"at {_when(start)}" if _when(start) == _when(end) else f"{_when(start)} to {_when(end)}"


def _techniques(report: CaseReport) -> List[Block]:
    blocks: List[Block] = [Heading(2, "ATT&CK techniques")]
    if not report.techniques:
        return blocks + [Para("Elrond tagged no ATT&CK techniques in this case.")]
    ordered = sorted(report.techniques.values(), key=lambda t: (-t.rows, t.tid))
    with_rows = [t for t in ordered if t.rows]
    without = [t for t in ordered if not t.rows]
    blocks.append(Para(f"{_plural(len(report.techniques), 'technique')}: {len(with_rows)} named by rows in the case's "
                       f"tables, each cited below, and {len(without)} recorded in {TECHNIQUES_FILE} with no row "
                       "naming it."))
    blocks.append(Table(["Technique", "Name", "Tactics", "Hosts", "Rows"],
                        [[[(t.tid, "b")], t.name, t.tactics, ", ".join(t.hosts), f"{t.rows:,}"] for t in ordered],
                        [2, 5, 4, 4, 1]))
    for technique in with_rows:
        blocks.append(Heading(3, f"{technique.tid} {technique.name}".strip()))
        files = sorted(technique.files.values(), key=lambda f: (f.host, -f.count, f.file))
        blocks.append(Para(f"{_plural(technique.rows, 'row')} in {_plural(len(files), 'table')} on "
                           f"{', '.join(technique.hosts)}."))
        cited = []
        for entry in files:
            for cite in entry.cites:
                cited.append([cite.host, _when(cite.time), *_cite_cells(cite), _excerpt(cite)])
        blocks.append(Table(["Host", "Time", "File", "Row", "Hash", "Row (excerpt)"], cited, [3, 4, 5, 1, 3, 10]))
        more = [entry for entry in files if entry.count > len(entry.cites)]
        if more:
            blocks.append(Para(f"Not cited above (filter the table on {technique.tid} in the case browser to list them):"))
            blocks.append(Bullets([[(f"{entry.host}: ", ""), (entry.file, "code"),
                                    (f", {_plural(entry.count - len(entry.cites), 'more row')}", "")] for entry in more]))
    if without:
        blocks.append(Heading(3, "Recorded without a row"))
        legacy = any(h.legacy_tables for h in report.hosts)
        why = (" while processing tables that are CSV and JSON from before rows carried their own techniques (the "
               "flagged rows in those tables are where to look)" if legacy else " for an artefact as a whole")
        blocks.append(Para([("Elrond recorded these in ", ""), (TECHNIQUES_FILE, "code"),
                            (f"{why}; no row in cooked/ or analysis/ names them, so there is no row to cite. Treat "
                             "them as leads to check, not as findings.", "")]))
        blocks.append(Table(["Technique", "Name", "Tactics"], [[t.tid, t.name, t.tactics] for t in without], [2, 6, 5]))
    return blocks


def _indicator_rows(indicators) -> List[List]:
    return [[i.kind, [(i.value, "code")], f"{i.count:,}", *_cite_cells(i.cite)] for i in indicators]


def _indicators(report: CaseReport) -> List[Block]:
    blocks: List[Block] = [Heading(2, "Indicators")]
    if not any(h.ioc_file or h.intel_file for h in report.hosts) and not report.threat_groups:
        return blocks + [Para("No indicators were extracted and no threat intelligence was matched (Elrond runs "
                              "without --extractIocs or --threatIntel don't).")]
    blocks.append(Para("Indicators are what Elrond extracted from the case's files (--extractIocs), not verdicts: each "
                       "is cited by its first row, and the occurrences are the rows it appears in."))
    for host in report.hosts:
        blocks.append(Heading(3, host.name))
        if not host.ioc_file:
            blocks.append(Para("No IOCs were extracted for this host."))
        else:
            distinct = sum(host.ioc_types.values())
            kinds = ", ".join(f"{count:,} {kind}" for kind, count in sorted(host.ioc_types.items()))
            blocks.append(Para([(f"{_plural(host.ioc_rows, 'occurrence')} of {_plural(distinct, 'distinct indicator')} "
                                 f"({kinds or 'none'}) in ", ""), (host.ioc_file, "code"), (".", "")]))
            if host.watchlisted:
                blocks.append(Para([("On the watchlist", "b"), (" (the IOC file or threat intelligence given to Elrond):", "")]))
                blocks.append(Table(["Type", "Indicator", "Occurrences", "File", "Row", "Hash"],
                                    _indicator_rows(host.watchlisted), [3, 6, 2, 4, 1, 3]))
            for kind in sorted(host.indicators, key=lambda k: (k not in ("IPv4 address", "IPv6 address", "domain"), k)):
                listed = host.indicators[kind]
                blocks.append(Para([(kind, "b"), (f": the {len(listed)} most frequent of {host.ioc_types.get(kind, 0):,}"
                                                  if host.ioc_types.get(kind, 0) > len(listed) else "", "")]))
                blocks.append(Table(["Type", "Indicator", "Occurrences", "File", "Row", "Hash"], _indicator_rows(listed),
                                    [3, 6, 2, 4, 1, 3]))
        if host.intel_file:
            blocks.append(Para([("Threat intelligence matches", "b"), (f": {_plural(len(host.intel), 'element')} in ", ""),
                                (host.intel_file, "code"), (", each cited by its first row.", "")]))
            blocks.append(Table(["Kind", "Element", "Rows", "File", "Row", "Hash"],
                                _indicator_rows(host.intel[:25]), [2, 7, 1, 4, 1, 3]))
            if len(host.intel) > 25:
                blocks.append(Para(f"{len(host.intel) - 25} more elements are in {host.intel_file}."))
    if report.threat_groups:
        blocks.append(Heading(3, "Threat groups"))
        blocks.append(Para([("Ranked by Elrond's threat intelligence matching in ", ""), (report.threat_groups_file, "code"),
                            (" (the case's own table): the Basis says what each rank rests on.", "")]))
        rows = [[fields.get("Rank", ""), fields.get("Group", ""), fields.get("Basis", ""),
                 fields.get("Techniques In Case", ""), cite.ref, [(_short(cite.row_hash), "code")]]
                for fields, cite in report.threat_groups[:15]]
        blocks.append(Table(["Rank", "Group", "Basis", "Techniques in case", "Row", "Hash"], rows, [1, 4, 4, 6, 1, 3]))
        if len(report.threat_groups) > 15:
            blocks.append(Para(f"{len(report.threat_groups) - 15} more groups are in {report.threat_groups_file}."))
    return blocks


def _integrity_result(host: HostReport) -> str:
    integrity = host.integrity
    counts = integrity.counts
    if integrity.checked:
        bad = sum(n for s, n in counts.items() if s != "verified")
        total = sum(counts.values())
        if not bad:
            return f"all {total:,} files match Gandalf's SHA-256"
        return f"{bad:,} of {total:,} files don't verify: see below"
    if integrity.gandalf:
        return ("not checked: Gandalf's log.meta has no archive-path hashes (an older collector)"
                if not integrity.summary or integrity.summary == "not checked" else f"recorded at extraction: {integrity.summary}")
    return "not a Gandalf acquisition: no collector manifest to check"


def _integrity(report: CaseReport) -> List[Block]:
    blocks: List[Block] = [Heading(2, "Evidence integrity"),
                           Para([("Gandalf records the SHA-256 of every file it collects in ", ""), ("log.meta", "code"),
                                 ("; before extracting an archive, Elrond hashes each file in it again and records the "
                                  "result per file in the host's ", ""), ("gandalf_integrity", "code"),
                                 (" table (verified, MISMATCH, missing, unhashed).", "")])]
    rows = []
    for host in report.hosts:
        counts = host.integrity.counts
        source = host.integrity.archive or ("Gandalf" if host.integrity.gandalf else "disk or memory image")
        rows.append([host.name, source, *(f"{counts.get(s, 0):,}" if host.integrity.checked else ""
                                          for s in ("verified", "MISMATCH", "missing", "unhashed")),
                     _integrity_result(host), [(host.integrity.file, "code")] if host.integrity.file else ""])
    blocks.append(Table(["Host", "Acquisition", "Verified", "MISMATCH", "Missing", "Unhashed", "Result", "Table"], rows,
                        [3, 3, 2, 2, 2, 2, 5, 4]))
    problems = [(host, cite) for host in report.hosts for cite in host.integrity.problems]
    if problems:
        blocks.append(Para("Files that didn't verify, each cited by its row in the integrity table:"))
        blocks.append(Table(["Host", "Row (excerpt)", "File", "Row", "Hash"],
                            [[host.name, cite.excerpt, *_cite_cells(cite)] for host, cite in problems], [3, 10, 4, 1, 3]))
        cut = [h.name for h in report.hosts if sum(n for s, n in h.integrity.counts.items() if s != "verified")
               > len(h.integrity.problems)]
        if cut:
            blocks.append(Para(f"More than {len(problems)} are listed in the integrity tables of {', '.join(cut)}."))
    return blocks


def _method(report: CaseReport) -> List[Block]:
    blocks: List[Block] = [Heading(2, "Method")]
    method = report.method
    if not method:
        blocks.append(Para(report.method_problem + "; the processing log below is what the case shows of it."))
    else:
        status = method.get("status", "")
        blocks.append(Para([("Elrond ", ""), (method.get("elrond", "") or "", ""),
                            (f"started {_when(method.get('started', ''))}", ""),
                            (f", finished {_when(method.get('finished', ''))}" if method.get("finished") else
                             ", and didn't record finishing (the run stopped, or is still going)", ""),
                            (f" ({status})." if status and status != "completed" else ".", ""),
                            (" From ", ""), (METHOD_FILE, "code"), (" in the case.", "")]))
        if method.get("command"):
            blocks.append(Para([("Command: ", "b"), (" ".join(method["command"]), "code")]))
        options = method.get("options") or {}
        if options:
            blocks.append(Table(["Option", "Value"], [[[(f"--{k}", "code")], _option(v)] for k, v in options.items()],
                                [2, 5]))
        sources = method.get("sources") or []
        if sources:
            blocks.append(Para([("Evidence: ", "b")] + _joined(sources)))
        tools = method.get("tools") or []
        if tools:
            blocks.append(Table(["Tool", "Version", "Path"],
                                [[t.get("name", ""), t.get("version", "") or "found; no version reported",
                                  [(t.get("path", ""), "code")]] for t in tools], [3, 6, 5]))
        missing = method.get("tools_missing") or []
        if missing:
            blocks.append(Para("Not found where Elrond ran: " + ", ".join(missing) + "."))
        runtime = ", ".join(f"{k} {v}" for k, v in (("Python", method.get("python")), ("on", method.get("platform"))) if v)
        if runtime:
            blocks.append(Para(runtime + "."))
    blocks.append(Heading(3, "Processing log"))
    if not report.audit_entries:
        blocks.append(Para(f"There's no {AUDIT_LOG} in the case."))
        return blocks
    blocks.append(Para([(f"{_plural(report.audit_entries, 'entry', 'entries')} in ", ""), (AUDIT_LOG, "code"),
                        (f", {_plural(report.failure_count, 'failure')}.", "")]))
    rows = []
    for host, stages in sorted(report.stages.items()):
        main = sorted(((s, n) for s, n in stages.items() if "/" not in s and len(s) <= 40), key=lambda x: -x[1])
        rest = sum(n for s, n in stages.items() if "/" in s or len(s) > 40)
        summary = ", ".join(f"{s} {n:,}" for s, n in main[:8]) + (f", per-file entries {rest:,}" if rest else "")
        rows.append([host, f"{sum(stages.values()):,}", summary])
    blocks.append(Table(["Host", "Entries", "Stages (entries)"], rows, [3, 1, 10]))
    if report.failures:
        blocks.append(Para("Failures, cited by their line in the audit log:"))
        blocks.append(Table(["Line", "Time", "Host", "Stage", "Entry"],
                            [[str(f.line), _when(f.time), f.host, f.stage, f.entry] for f in report.failures],
                            [1, 3, 3, 4, 8]))
        if report.failure_count > len(report.failures):
            blocks.append(Para(f"{report.failure_count - len(report.failures):,} more failures are in {AUDIT_LOG}."))
    return blocks


def _option(value) -> str:
    if value is True:
        return "on"
    if isinstance(value, list):
        return ", ".join(str(v) for v in value)
    return str(value)


def _joined(values: Iterable[str]) -> List:
    out: List = []
    for number, value in enumerate(values):
        if number:
            out.append(("; ", ""))
        out.append((str(value), "code"))
    return out


def uncurated_blocks(report: CaseReport) -> List[Block]:
    return ([Heading(1, f"{report.case}: case report")] + _introduction(report) + _hosts(report)
            + _techniques(report) + _indicators(report) + _integrity(report) + _method(report))


# ---- the curated report ----

def _finding_state(finding: Dict) -> str:
    intact = finding.get("intact")
    if intact is None:
        return "not checked against the case"
    return "unchanged since it was flagged" if intact else "ROW CHANGED since it was flagged: check it again before relying on it"


def curated_blocks(report: CaseReport, findings: List[Dict], notes: List[Dict]) -> List[Block]:
    """Confirmed findings first, then open leads and dismissed rows, then the uncurated report.
    ``findings`` are the case browser's (case_routes.CaseStore), each with ``intact`` from its check."""
    confirmed = [f for f in findings if f["status"] == "confirmed"]
    rest = [f for f in findings if f["status"] != "confirmed"]
    by_finding: Dict[Optional[int], List[Dict]] = {}
    for note in notes:
        by_finding.setdefault(note.get("finding_id"), []).append(note)
    changed = [f for f in confirmed if f.get("intact") is False]
    blocks: List[Block] = [
        Heading(1, f"{report.case}: case report"),
        Para([("Generated by Rowanholt on ", ""), (_when(report.generated), ""), (" from the case directory ", ""),
              (report.root, "code"), (" and its analysts' findings. Confirmed findings come first; Appendix A lists "
                                      "the open leads and dismissed rows, and Appendix B is Elrond's report from the "
                                      "case alone (techniques, indicators, integrity and method), unreviewed.", "")]),
        Para(f"{_plural(len(confirmed), 'confirmed finding')}, {_plural(sum(f['status'] == 'lead' for f in findings), 'open lead')}, "
             f"{sum(f['status'] == 'benign' for f in findings):,} dismissed as benign."),
    ]
    if changed:
        blocks.append(Para([("Warning: ", "b"), (f"{_plural(len(changed), 'confirmed finding')} no longer match the row "
                                                 "they were flagged on (a re-run changed the case): "
                                                 + ", ".join(f"#{f['id']}" for f in changed) + ".", "")]))
    if by_finding.get(None):
        blocks.append(Heading(2, "Case notes"))
        for note in by_finding[None]:
            blocks += [Para([(f"{note['author']}, {_when(note.get('created_at') or '')}", "i")]), Para([(note["body"], "raw")])]
    blocks.append(Heading(2, "Confirmed findings"))
    if not confirmed:
        blocks.append(Para("No findings have been confirmed yet: flag rows in the case browser and confirm them as they "
                           "hold up. Everything Elrond found is in Appendix B."))
    for host in sorted({f["host"] for f in confirmed}):
        blocks.append(Heading(3, host))
        for f in (f for f in confirmed if f["host"] == host):
            technique = f" ({_technique_label(report, f['technique'])})" if f.get("technique") else ""
            blocks.append(Heading(4, f"#{f['id']} {f['title']}{technique}"))
            blocks.append(Para([("Row: ", "b"), (f["artefact"], "code"), (f" row {f['row_ref']}, hash ", ""),
                                (_short(f["row_hash"]), "code"), (f"; {_finding_state(f)}.", "")]))
            blocks.append(Para(f"Flagged by {f['author']} on {_when(f.get('created_at') or '')}"
                               + (f", last changed {_when(f['updated_at'])}" if f.get("updated_at") and
                                  f.get("updated_at") != f.get("created_at") else "") + "."))
            if f.get("excerpt"):
                blocks.append(Quote(f["excerpt"]))
            for note in by_finding.get(f["id"], []):
                blocks.append(Para([(f"{note['author']}, {_when(note.get('created_at') or '')}: ", "i"), (note["body"], "raw")]))
    blocks.append(Heading(2, "Appendix A: open leads and dismissed rows"))
    if not rest:
        blocks.append(Para("None."))
    else:
        blocks.append(Table(["#", "Status", "Host", "Title", "Technique", "File", "Row", "Hash", "Row now"],
                            [[str(f["id"]), f["status"], f["host"], f["title"], f.get("technique") or "",
                              [(f["artefact"], "code")], f["row_ref"], [(_short(f["row_hash"]), "code")],
                              "unchanged" if f.get("intact") else "changed" if f.get("intact") is False else ""]
                             for f in rest], [1, 2, 3, 5, 2, 5, 1, 3, 2]))
    appendix = uncurated_blocks(report)[1:]  # without its title
    blocks.append(Heading(2, "Appendix B: Elrond's report from the case"))
    return blocks + document.shifted(appendix, 1)


# ---- output ----

def render(blocks: List[Block], fmt: str, title: str) -> bytes:
    if fmt == "markdown":
        return document.markdown(blocks).encode("utf-8")
    if fmt == "docx":
        return document.docx(blocks, title)
    raise ValueError(f"format is one of {', '.join(FORMATS)}")


def uncurated_report(report: CaseReport, fmt: str) -> bytes:
    return render(uncurated_blocks(report), fmt, f"{report.case}: case report")


def curated_report(report: CaseReport, findings: List[Dict], notes: List[Dict], fmt: str) -> bytes:
    return render(curated_blocks(report, findings, notes), fmt, f"{report.case}: case report")


def report_name(case: str, fmt: str) -> str:
    return re.sub(r"[^\w.+-]", "_", f"{case}_report") + SUFFIXES[fmt]


def write_reports(path, out_dir=None, formats: Iterable[str] = FORMATS, case_number: str = "",
                  progress=None) -> List[Path]:
    """The uncurated report of the case at ``path`` in each format, written to ``out_dir`` (the
    case's folder by default); the paths written."""
    report = gather(path, case_number, progress)
    target = Path(out_dir) if out_dir else Path(report.root)
    target.mkdir(parents=True, exist_ok=True)
    written = []
    for fmt in formats:
        out = target / report_name(report.case, fmt)
        out.write_bytes(uncurated_report(report, fmt))
        logger.info(f"Wrote {out}")
        written.append(out)
    return written
